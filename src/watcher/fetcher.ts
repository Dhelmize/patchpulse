import { getConfig } from '../config/env.js';

interface FetchOptions {
  timeout?: number;
  retries?: number;
  headers?: Record<string, string>;
}

export async function fetchWithRetry(url: string, options: FetchOptions = {}): Promise<string> {
  const {
    timeout = parseInt(getConfig().REQUEST_TIMEOUT),
    retries = parseInt(getConfig().MAX_RETRIES),
    headers = {},
  } = options;

  const defaultHeaders = {
    'User-Agent': getConfig().USER_AGENT,
    'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
    'Accept-Language': 'en-US,en;q=0.5',
    ...headers,
  };

  let lastError: Error | null = null;

  for (let attempt = 0; attempt <= retries; attempt++) {
    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), timeout);

      const response = await fetch(url, {
        headers: defaultHeaders,
        signal: controller.signal,
      });

      clearTimeout(timeoutId);

      if (!response.ok) {
        throw new Error(`HTTP ${response.status}: ${response.statusText}`);
      }

      const content = await response.text();
      return content;
    } catch (error) {
      lastError = error as Error;

      if (attempt < retries) {
        // Exponential backoff
        const delay = Math.pow(2, attempt) * 1000;
        await new Promise(resolve => setTimeout(resolve, delay));
      }
    }
  }

  throw new Error(`Failed to fetch ${url} after ${retries + 1} attempts: ${lastError?.message}`);
}
